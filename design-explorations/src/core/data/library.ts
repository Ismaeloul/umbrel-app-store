const rand = mulberry32(777);

function items(listaId: string, rows: [string, string, string?][]): Item[] {
  return rows.map(([title, category, alias]) => ({
    id: hashFrom(rand),
    title,
    alias,
    type: 'web',
    category,
    date: new Date(Date.now() - Math.floor(rand() * 5) * 86400000).toISOString(),
    fromWebSync: true,
    ih: false,
    listaId,
  }));
}

